// tests/e2e/tier1_features/f11_jaml_ui_rebuild.test.mjs
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import fs from 'node:fs';
import { PATHS, exists } from '../helpers/env.mjs';
import { runCli } from '../helpers/cli_runner.mjs';

describe('Feature 11: jaml-ui Rebuild & Validation', () => {
  it('F11-1: pnpm test passes all unit test suites in jaml-ui', () => {
    const result = runCli('pnpm', ['test'], { cwd: PATHS.jamlUi, timeoutMs: 30000 });
    assert.equal(result.exitCode, 0, `Test failed with code ${result.exitCode}:\n${result.stderr || result.stdout}`);
  });

  it('F11-2: pnpm typecheck completes with 0 TypeScript compilation errors', () => {
    const result = runCli('pnpm', ['typecheck'], { cwd: PATHS.jamlUi, timeoutMs: 30000 });
    assert.equal(result.exitCode, 0, `Typecheck failed with code ${result.exitCode}:\n${result.stderr || result.stdout}`);
  });

  it('F11-3: pnpm build bundles all entrypoints to dist/ without error', () => {
    const result = runCli('pnpm', ['build'], { cwd: PATHS.jamlUi, timeoutMs: 45000 });
    assert.equal(result.exitCode, 0, `Build failed with code ${result.exitCode}:\n${result.stderr || result.stdout}`);
  });

  it('F11-4: dist/index.js exists and exceeds minimal bundle threshold', () => {
    const file = path.join(PATHS.jamlUi, 'dist', 'index.js');
    assert.equal(exists(file), true, `dist/index.js not found at ${file}`);
    const stat = fs.statSync(file);
    assert.ok(stat.size > 1000, `Bundle size too small: ${stat.size} bytes`);
  });

  it('F11-5: dist/ui.js and dist/ui.d.ts exist', () => {
    const jsFile = path.join(PATHS.jamlUi, 'dist', 'ui.js');
    const dtsFile = path.join(PATHS.jamlUi, 'dist', 'ui.d.ts');
    assert.equal(exists(jsFile), true, 'dist/ui.js missing');
    assert.equal(exists(dtsFile), true, 'dist/ui.d.ts missing');
  });

  it('F11-6: dist/ui/jimbo.css stylesheet is generated by build', () => {
    const cssFile = path.join(PATHS.jamlUi, 'dist', 'ui', 'jimbo.css');
    assert.equal(exists(cssFile), true, `dist/ui/jimbo.css missing at ${cssFile}`);
  });
});
